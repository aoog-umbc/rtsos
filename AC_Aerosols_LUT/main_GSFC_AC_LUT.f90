	WRITE(*,*) 'USEAGE:'
	WRITE(*,*) 'rtsos_MODIS_LUT.exe input.file'
	WRITE(*,*) ''
	STOP
ENDIF


!  First argument is the input file
CALL GETARG(1,INFILE)
OPEN(unit=1,file=INFILE,status='old')

! ----- new read in from the input file Nov. 28 2022
READ(1,*)NWV
READ(1,*)WAVELENGTH_MICRON_REF
READ(1,'(A)')CFILE_INSTRUMENT
READ(1,'(A)')aux_dir
READ(1,'(A)')atmos_dir
READ(1,'(A)')Mie_Database_Dir
READ(1,*)MIE_TABLE_CAL
! -----new read in from the input file Nov. 28 2022

READ(1,*)IAEROSOL
READ(1,*)AeroFMF              ! user input value used only when iaerosol==-1
READ(1,*)RH_simu
READ(1,*)WNDSPD
READ(1,*)THETA0
READ(1,*)TAU_REF
READ(1,*)PRESSURE_SURFACE      ! surface pressure in mb
READ(1,*)H2O_COLUMN            !water vapor column amount in cm
READ(1,*)OZONE_COLUMN          !ozone column amount in Dobson Unit

READ(1,*)INTTMP
	IF(INTTMP == 0) THEN
		WCFLG_INPUT=.false.
	ELSE
		WCFLG_INPUT=.true.
	ENDIF


READ(1,*)I_SURFACE_ROUGHNESS_PARA

READ(1,*)INTTMP
	IF(INTTMP == 0) THEN
		DIFFUSE_TRANSMITTANCE=.false.
	ELSE
		DIFFUSE_TRANSMITTANCE=.true.
	ENDIF

READ(1,*)INTTMP
	IF(INTTMP == 0) THEN
        SPHERICAL_SHELL_SINGLESCATTERING_CORRECTION=.false.
    ELSE
        SPHERICAL_SHELL_SINGLESCATTERING_CORRECTION=.true.
	ENDIF

READ(1,'(A)')CFILE_AP              ! file name of the atmospheric profiles
READ(1,'(A)')OUTFILE                ! file name for output
close(1)

IF(index(CFILE_INSTRUMENT,'#')>1) &
  CFILE_INSTRUMENT=trim(CFILE_INSTRUMENT(1:index(CFILE_INSTRUMENT,'#')-1))
IF(index(aux_dir,'#')>1) &
  aux_dir=trim(aux_dir(1:index(aux_dir,'#')-1))
IF(index(atmos_dir,'#')>1) &
  atmos_dir=trim(atmos_dir(1:index(atmos_dir,'#')-1))
IF(index(Mie_Database_Dir,'#')>1) &
   Mie_Database_Dir=trim(Mie_Database_Dir(1:index(Mie_Database_Dir,'#')-1))
IF(index(CFILE_AP,'#')>1) &
   CFILE_AP=trim(CFILE_AP(1:index(CFILE_AP,'#')-1))
IF(index(OUTFILE,'#')>1) &
   OUTFILE=trim(OUTFILE(1:index(OUTFILE,'#')-1))
IF(MIE_TABLE_CAL==1)TAU_REF=1.0D0

write(*,*)'atmos_dir=',atmos_dir
write(*,*)'Mie_Database_Dir=',Mie_Database_Dir
write(*,*)'MIE_TABLE_CAL=',MIE_TABLE_CAL
write(*,*)'aux_dir=',aux_dir
write(*,*)'atmospheric profile file=',CFILE_AP
write(*,*)'OUTFILE=',OUTFILE

CFILE_INSTRUMENT=TRIM(aux_dir)//'/'//trim(CFILE_INSTRUMENT)

SURFACE_GLINT_FLAG = .TRUE.

IF(IAEROSOL>0)THEN
	INTARR=MINLOC(ABS(RH-RH_simu))
	IRH=INTARR(1)
	IF(abs(RH(IRH)-RH_simu)>1.0e-4) THEN
	   WRITE(*,*)'INPUT RH_simu VALUE:',RH_simu,'NOT IN RH TABLE'
	   WRITE(*,*)'RELATIVE HUMIDTY TABLE:', IRH, RH(IRH)
	ENDIF
ENDIF

ALLOCATE(WV(NWV),AW(NWV),BW(NWV),OPTRAY(NWV),DEPOLRAY(NWV),RINDX_WATER(NWV))

! read in wv,optray
Open(unit=1,file=CFILE_INSTRUMENT,STATUS='OLD',ACTION='READ')
READ(1,*)
DO IWV=1,NWV
   READ(1,*)INTTMP,WV(IWV),RTMP,RTMP1,RTMP2,OPTRAY(IWV),DEPOLRAY(IWV)
ENDDO
CLOSE(1)

IF(IAEROSOL>20 .AND. NWV .NE. NWV_DUST) STOP 'IAEROSOL > 20 ONLY PREPARED FOR BO-CAI GAO TABLE'

!MIE_TABLE_CAL=3 ! changed to read in from input file. Nov. 28 2022 pwz
sngmode=.false.

IF(IAEROSOL>20)THEN
	INTARR=MINLOC(abs(WAVELENGTH_MICRON_REF-WV_DUST))
	IWVWV_DUST=INTARR(1)
ELSE
    CALL WV_REF_ASSIGN(WAVELENGTH_MICRON_REF) ! aerosol optical depth reference wavelength
ENDIF

RATIO_INCR=0.01D0
LBDO_LD=0.0
FLAM=1.0

! aerosol profile will be given by Braslau, JAM, 1973
NTLYERA=NDET-2

CALL Atmosphere_Profile_READIN(CFILE_AP)
CALL Surface_Pressure_Rescale(PRESSURE_SURFACE)
CALL GAS_COLUMN_RESCALE(OZONE_COLUMN,H2O_COLUMN)

ALLOCATE(ALT_LYRA(NTLYERA+1),TAUR(NWV,NTLYERA),DEPOL_A(NWV,NTLYERA))

! USE ALT_DET AS ALT_LYRA, IF DIFFERENT SET OF ALT_LYRA IS NEEDED
! LET NTLYERA= A NUMBER, AND GIVE ALT_LYRA IN THE FOLLOWING
! ALT_DET HAS TO BE A SUBSET OF ALT_LYRA.

ALT_LYRA=ALT_DET

CALL TAURCAL(NTLYERA,ALT_LYRA)

DO IWV=1,NWV
	RTMP=0.0D0
	DO INTTMP=1,NTLYERA
	   RTMP=RTMP+TAUR(IWV,INTTMP)
!	   write(*,*)'wv,taur',WV(IWV),TAUR(IWV,INTTMP),rtmp
	ENDDO
    TAUR(IWV,:)=TAUR(IWV,:)/RTMP*OPTRAY(IWV)
!    WRITE(*,*)'TOTAL RAYLEIGH OPTICAL DEPTH',RTMP,'IS RESCALED TO',OPTRAY(IWV)
ENDDO

TEMPERATURE=20.0D0
SALINITY=37.0D0
DO IWV=1,NWV
  WAVELENGTH_NANOMETER=WV(IWV)*1000.0d0
  CALL WATER_REFRACTIVE_INDEX(WAVELENGTH_NANOMETER,TEMPERATURE,SALINITY,RINDX_WATER(IWV))
!  WRITE(*,*)'WV(IWV),RINDX_WATER(IWV)=',WV(IWV),RINDX_WATER(IWV)
ENDDO

! ASSIGN RTSOS PARAMETERS
NTHETAOUT=41*2
