CALL MUPHIOUTASS(NTHETAOUT,NPHIOUT,MUOUT,PHIOUT)

NCOLINPUT=40
NQUADAINPUT=48
NQUADOINPUT=60
NUMMIEUSE=1
MAXLORDINPUT=48
MAXMORDINPUT=30
NMBREINPUT=1.338
NMBIMINPUT=0.0
IF(DIFFUSE_TRANSMITTANCE)THEN
  NCOLINPUT=30
  MAXMORDINPUT=1
ENDIF
NTLYERO=1

NTLYER=NTLYERA+NTLYERO
NUMMIERT=NTLYERA

! NUMBER OF INPUT LINES INCLUDING DETECTORS AND ATMOSPEHRIC AND OCEANIC LAYERS
NREC=NTLYERA+NDET+3

ALLOCATE(NUMMIEANGINPUT(NUMMIERT),PHMXDATASTREAM(NUMMIERT,NUMMIEANGMAX,0:6))

ALLOCATE(DIRAD(NDET,2),DSTOKES(NDET,NTHETAOUT,NPHIOUT,4))

ALLOCATE(DIRADFULL(NDET,NWV,2),DSTOKESFULL(NDET,NWV,NTHETAOUT,NPHIOUT,4),&
		DSTOKESFULL_TOA_Glint(NWV,NTHETAOUT,NPHIOUT,4))

ALLOCATE(RECDATASTREAM(NREC,7),TAU_TG(NWV,NTLYERA),   &
         TAU_ARSL_TOTAL(NWV,NTLYERA),PNDLY(NTLYERA),ARSLND1(NTLYER),ARSLND2(NTLYER), &
         REFF1(NUMMIEUSE),REFF2(NUMMIEUSE),VEFF1(NUMMIEUSE),         &
         VEFF2(NUMMIEUSE), MRR1(NWV+1,NUMMIEUSE),MRI1(NWV+1,NUMMIEUSE),  &
         MRR2(NWV+1,NUMMIEUSE),MRI2(NWV+1,NUMMIEUSE))

CALL SURFACE_GLINT_ALLO(NDET,NTHETAOUT,NPHIOUT)

ARSLND1=0.0d0
ARSLND2=0.0d0
REFF1=0.0d0
REFF2=0.0d0
VEFF1=0.0d0
VEFF2=0.0d0
MRR1=1.0d0
MRR2=1.0d0
MRI1=1.0d0
MRI2=1.0d0

TAU_TG=0.0D0
TAU_ARSL_TOTAL=0.0D0

IF(IAEROSOL<=20) CALL ARSL_INDX_INIT(NWV, WV)
CALL ARSL_VERP_INIT(NTLYERA,ALT_LYRA,PNDLY)


MU_IN=COS((180.0-THETA0)/180.*PI)

IF(IAEROSOL==0 .or. IAEROSOL<-1 .OR. IAEROSOL> 30) &
		STOP 'WARNING! IAEROSOL VALUE SHOULD BE -1, or BETWEEN 1 AND 30'

IF(IAEROSOL >20 .and. IAEROSOL <= 30) CALL DUST_PHASE_MATRIX_READIN


IF(IAEROSOL==10) THEN
	sngmode=.true.
ELSE
	sngmode=.FALSE.
ENDIF

! check file existance

OUTFILE=TRIM(OUTFILE)//'.h5'
INQUIRE(FILE=OUTFILE, EXIST=file_e)
IF(file_e) stop 'output file exist'

DO IWV=1,NWV+1
  IF(IAEROSOL==1)THEN !rural
       MRR1(IWV,:)=MR_TRPOSPHERE(IWV,IRH)
       MRI1(IWV,:)=MI_TRPOSPHERE(IWV,IRH)
       MRR2(IWV,:)=MR_RURALC(IWV,IRH)
       MRI2(IWV,:)=MI_RURALC(IWV,IRH)
  ELSEIF(IAEROSOL==2)THEN ! URBAN
       MRR1(IWV,:)=MR_URBANF(IWV,IRH)
       MRI1(IWV,:)=MI_URBANF(IWV,IRH)
       MRR2(IWV,:)=MR_URBANC(IWV,IRH)
       MRI2(IWV,:)=MI_URBANC(IWV,IRH)
  ELSEIF(IAEROSOL==3)THEN ! URBAN A
       MRR1(IWV,:)=MR_URBANAF(IWV,IRH)
       MRI1(IWV,:)=MI_URBANAF(IWV,IRH)
       MRR2(IWV,:)=MR_URBANAC(IWV,IRH)
       MRI2(IWV,:)=MI_URBANAC(IWV,IRH)
  ELSEIF(IAEROSOL==4)THEN  ! URBAN A1
       MRR1(IWV,:)=MR_URBANA1F(IWV,IRH)
       MRI1(IWV,:)=MI_URBANA1F(IWV,IRH)
       MRR2(IWV,:)=MR_URBANA1C(IWV,IRH)
       MRI2(IWV,:)=MI_URBANA1C(IWV,IRH)
    ELSEIF(IAEROSOL==5)THEN! URBAN A2
       MRR1(IWV,:)=MR_URBANA2F(IWV,IRH)
       MRI1(IWV,:)=MI_URBANA2F(IWV,IRH)
       MRR2(IWV,:)=MR_URBANA2C(IWV,IRH)
       MRI2(IWV,:)=MI_URBANA2C(IWV,IRH)
    ELSEIF(IAEROSOL==6)THEN! URBAN A3
       MRR1(IWV,:)=MR_URBANA3F(IWV,IRH)
       MRI1(IWV,:)=MI_URBANA3F(IWV,IRH)
       MRR2(IWV,:)=MR_URBANA3C(IWV,IRH)
       MRI2(IWV,:)=MI_URBANA3C(IWV,IRH)
    ELSEIF(IAEROSOL>=7 .AND. IAEROSOL<=9)THEN! MARINETIME
       MRR1(IWV,:)=MR_TRPOSPHERE(IWV,IRH)
       MRI1(IWV,:)=MI_TRPOSPHERE(IWV,IRH)
       MRR2(IWV,:)=MR_OCEANIC(IWV,IRH)
       MRI2(IWV,:)=MI_OCEANIC(IWV,IRH)
    ELSEIF(IAEROSOL==10)THEN
       MRR1(IWV,:)=MR_TRPOSPHERE(IWV,IRH)
       MRI1(IWV,:)=MI_TRPOSPHERE(IWV,IRH)
       MRR2(IWV,:)=1.0
       MRI2(IWV,:)=0.0
    ELSEIF(IAEROSOL==-1 .or. (IAEROSOL>10 .AND. IAEROSOL<=20))THEN
!		MRR1(IWV,:)=MR_ZIAF(IWV,IRH)
!		MRI1(IWV,:)=MI_ZIAF(IWV,IRH)
!		MRR2(IWV,:)=MR_ZIAC(IWV,IRH)
!		MRI2(IWV,:)=MI_ZIAC(IWV,IRH)

		XARRY=RH

		YARRY=MR_ZIAF(IWV,:)
        MRR1(IWV,:)=Func_UVIP3P(NRH,XARRY,YARRY,RH_simu,2)
		YARRY=MI_ZIAF(IWV,:)
		MRI1(IWV,:)=Func_UVIP3P(NRH,XARRY,YARRY,RH_simu,2)
		YARRY=MR_ZIAC(IWV,:)
		MRR2(IWV,:)=Func_UVIP3P(NRH,XARRY,YARRY,RH_simu,2)
		YARRY=MI_ZIAC(IWV,:)
		MRI2(IWV,:)=Func_UVIP3P(NRH,XARRY,YARRY,RH_simu,2)

    ELSEIF(IAEROSOL>20 .and. IAEROSOL <= 30)THEN
! DUST AEROSOL MODELS
       MRR1(IWV,:)=MR_DUST_NONSPHER(IWV)
       MRI1(IWV,:)=MI_DUST_NONSPHER(IWV)
       MRR2(IWV,:)=MR_DUST_NONSPHER(IWV)
       MRI2(IWV,:)=MI_DUST_NONSPHER(IWV)
    ENDIF
ENDDO

  IF(IAEROSOL==1)THEN
       REFF1(:)=RTROPOSPHERE(IRH)
       REFF2(:)=RRURALC(IRH)
  ELSEIF(IAEROSOL>=2 .AND. IAEROSOL<=6)THEN
       REFF1(:)=RURBANF(IRH)
       REFF2(:)=RURBANC(IRH)
  ELSEIF(IAEROSOL>=7 .AND. IAEROSOL<=9)THEN
       REFF1(:)=RTROPOSPHERE(IRH)
       REFF2(:)=ROCEANIC(IRH)
  ELSEIF(IAEROSOL==10)THEN
       REFF1(:)=RTROPOSPHERE(IRH)
       REFF2(:)=0.0D0
  ELSEIF(IAEROSOL==-1 .OR. (IAEROSOL>=11 .AND. IAEROSOL<=20))THEN
		!REFF1(:)=exp(log(RZIAF(IRH))-3.0*SIGF_ZIA*SIGF_ZIA)
		! Rg in number space read Eq.3a in Ahmad 2000 for details
		!REFF2(:)=exp(log(RZIAC(IRH))-3.0*SIGC_ZIA*SIGC_ZIA)

        RTMP=Func_UVIP3P(NRH,RH,RZIAF,RH_simu,3)
		REFF1(:)=exp(log(RTMP)-3.0*SIGF_ZIA*SIGF_ZIA)
		! Rg in number space read Eq.3a in Ahmad 2000 for details
        RTMP=Func_UVIP3P(NRH,RH,RZIAC,RH_simu,3)
		REFF2(:)=exp(log(RTMP)-3.0*SIGC_ZIA*SIGC_ZIA)

  ELSEIF(IAEROSOL>20)THEN
       RTMP=EXP(2.5*SIGMAF_DUST*SIGMAF_DUST) ! EFFECTIVE RADIUS TO RG
       REFF1(:)=RF_DUST/RTMP  ! EFFECTIVE RADIUS TO RG

       RTMP=EXP(2.5*SIGMAC_DUST*SIGMAC_DUST) ! EFFECTIVE RADIUS TO RG
       REFF2(:)=RC_DUST/RTMP  ! EFFECTIVE RADIUS TO RG
  ENDIF

  IF(IAEROSOL>=1 .and. IAEROSOL<=10)THEN
     VEFF1(:)=SIGF_SF
     VEFF2(:)=SIGC_SF
  ELSEIF(IAEROSOL==-1 .or. (IAEROSOL>=11 .and. IAEROSOL<=20)) THEN
     VEFF1(:)=SIGF_ZIA
     VEFF2(:)=SIGC_ZIA
  ELSEIF(IAEROSOL>=21 .and. IAEROSOL<=30)THEN
     VEFF1(:)=SIGMAF_DUST
     VEFF2(:)=SIGMAC_DUST
  ENDIF

  IF(IAEROSOL>=1 .and. IAEROSOL<=6)THEN
     ARSLND1=0.999875*PNDLY
     ARSLND2=0.000125*PNDLY
  ELSEIF(IAEROSOL==7)THEN
     ARSLND1=0.99*PNDLY
     ARSLND2=0.01*PNDLY
  ELSEIF(IAEROSOL==8)THEN
     ARSLND1=0.995*PNDLY
     ARSLND2=0.005*PNDLY
  ELSEIF(IAEROSOL==9)THEN
     ARSLND1=0.998*PNDLY
     ARSLND2=0.002*PNDLY
  ELSEIF(IAEROSOL==10)THEN
     ARSLND1=PNDLY
     ARSLND2=0.0D0
  ELSEIF(IAEROSOL==-1 .or. IAEROSOL>=11)THEN
     IF(IAEROSOL>=11 .and. IAEROSOL<=20)THEN
        INTTMP=IAEROSOL-10
        AeroFMF=RATIO_FINE_MODE_ZIA(INTTMP)
	 ELSEIF(IAEROSOL>20)THEN
        INTTMP=IAEROSOL-20
        AeroFMF=RATIO_FINE_MODE_ZIA(INTTMP)
     ELSEIF(IAEROSOL==-1)THEN
        IF(AeroFMF<0.0D0 .OR.AeroFMF>1.0D0) THEN
           WRITE(*,*)'INPUT AeroFMF=',AeroFMF,' IS OUT OF 0-1'
           STOP 'STOPING DUE TO INVALID AeroFMF VALUE'
	    ENDIF
     ENDIF

     RTMP=4.0D0*PI*(REFF1(1)**3)/3.0D0
     RTMP=AeroFMF/RTMP*EXP(-4.5D0*VEFF1(1)*VEFF1(1))
     RTMP1=4.0D0*PI*(REFF2(1)**3)/3.0D0
     RTMP1=(1.0D0-AeroFMF)/RTMP1*EXP(-4.5D0*VEFF2(1)*VEFF2(1))
     RTMP=RTMP/(RTMP+RTMP1)
     ARSLND1=RTMP*PNDLY
     ARSLND2=(1.0D0-RTMP)*PNDLY
 !    WRITE(*,*)'FINE MODE NUMBER DENSITY=',sum(ARSLND1)
 !    WRITE(*,*)'COARSE MODE NUMBER DENSITY=',sum(ARSLND2)
  ENDIF


 ! CONVERT TO EFFECT RADIUS AND VARIANCE BEFORE CALL SPHER_INTERFACE
  VEFF1=VEFF1*VEFF1
  VEFF2=VEFF2*VEFF2

  REFF1=REFF1*EXP(2.5D0*VEFF1)
  REFF2=REFF2*EXP(2.5D0*VEFF2)
  VEFF1=EXP(VEFF1)-1.0D0
  VEFF2=EXP(VEFF2)-1.0D0

  IF(IAEROSOL<=20)THEN
	  NDISTR=2
	  CALL SPHER_INTERFACE(NDISTR,REFF1(1),VEFF1(1),WV_REF,MRR1(NWV+1,1),MRI1(NWV+1,1),&
			AA1,BB1,AA2,BB2,GAMMAI,REFFO,VEFFO,AREA,CEXT,CSCAT,NANGMIE_LOCAL,PHMXMIE_LOCAL)
	  IF(.NOT.sngmode)THEN
		CALL SPHER_INTERFACE(NDISTR,REFF2(1),VEFF2(1),WV_REF,MRR2(NWV+1,1),MRI2(NWV+1,1),&
