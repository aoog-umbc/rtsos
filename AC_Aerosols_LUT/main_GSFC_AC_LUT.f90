	CSCAT1=CSCATf_PART(IWV)

	CEXT2=CEXTc_PART(IWV)
	CSCAT2=CSCATc_PART(IWV)

	PHMXDATA_TMP1=0.0d0
	DO IMIE=1,NUMMIEUSE
	  PHMXDATA_TMP1(IMIE,1:NANGMIE_LOCAL,0)=SCAT_ANG_PART
	  PHMXDATA_TMP1(IMIE,1:NANGMIE_LOCAL,1:6)=PHASE_MATRf_PART(IWV,1:NANGMIE_LOCAL,1:6)
	ENDDO

	PHMXDATA_TMP2=0.0d0
	DO IMIE=1,NUMMIEUSE
	  PHMXDATA_TMP2(IMIE,1:NANGMIE_LOCAL,0)=SCAT_ANG_PART
	  PHMXDATA_TMP2(IMIE,1:NANGMIE_LOCAL,1:6)=PHASE_MATRc_PART(IWV,1:NANGMIE_LOCAL,1:6)
	ENDDO

ENDIF

IF(IAEROSOL>20)THEN

	IMIE=1

	NANGMIE_LOCAL=NUM_SCAT_ANG_DUST
	CEXT1=EXTINCTION_CROSS_SECTION_DUSTF(IWV)
	CSCAT1=SCATTERING_CROSS_SECTION_DUSTF(IWV)

	PHMXDATA_TMP1(IMIE,1:NUM_SCAT_ANG_DUST,0)=SCAT_ANG_DUST(1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP1(IMIE,1:NUM_SCAT_ANG_DUST,1)=P11F_DUST(IWV,1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP1(IMIE,1:NUM_SCAT_ANG_DUST,2)=P22F_DUST(IWV,1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP1(IMIE,1:NUM_SCAT_ANG_DUST,3)=P33F_DUST(IWV,1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP1(IMIE,1:NUM_SCAT_ANG_DUST,4)=P44F_DUST(IWV,1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP1(IMIE,1:NUM_SCAT_ANG_DUST,5)=P12F_DUST(IWV,1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP1(IMIE,1:NUM_SCAT_ANG_DUST,6)=P34F_DUST(IWV,1:NUM_SCAT_ANG_DUST)

	CEXT2=EXTINCTION_CROSS_SECTION_DUSTC(IWV)
	CSCAT2=SCATTERING_CROSS_SECTION_DUSTC(IWV)
	PHMXDATA_TMP2(IMIE,1:NUM_SCAT_ANG_DUST,0)=SCAT_ANG_DUST(1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP2(IMIE,1:NUM_SCAT_ANG_DUST,1)=P11C_DUST(IWV,1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP2(IMIE,1:NUM_SCAT_ANG_DUST,2)=P22C_DUST(IWV,1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP2(IMIE,1:NUM_SCAT_ANG_DUST,3)=P33C_DUST(IWV,1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP2(IMIE,1:NUM_SCAT_ANG_DUST,4)=P44C_DUST(IWV,1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP2(IMIE,1:NUM_SCAT_ANG_DUST,5)=P12C_DUST(IWV,1:NUM_SCAT_ANG_DUST)
	PHMXDATA_TMP2(IMIE,1:NUM_SCAT_ANG_DUST,6)=P34C_DUST(IWV,1:NUM_SCAT_ANG_DUST)

ENDIF

! BELOW THIS LINE I HAVE ASSUMED ONE MIE FOR ALL LAYERS
! OTHERWISE NEED TO DO APPROPERIATE CHANGES !!!!!!!!!!!!!!!!

NUMMIEANGINPUT=NANGMIE_LOCAL
IMIE=1
DO ITLYER=1,NTLYERA
  PHMXDATASTREAM(ITLYER,1:NUMMIEANGMAX,0)=PHMXDATA_TMP1(IMIE,1:NUMMIEANGMAX,0)
ENDDO
!call date_and_time(values=time_array_0)
!start_time = time_array_0 (5) * 3600 + time_array_0 (6) * 60 &
!           + time_array_0 (7) + 0.001 * time_array_0 (8)

!DETECTOR AT THE TOA

IMIE=1

DO IREC=1,2*(NTLYERA+1)
  IF(MOD(IREC,2)==1)THEN
    RECDATASTREAM(IREC,1)=INDXDETECTOR
    CYCLE
  ENDIF
  ITLYERA=IREC/2
  IF(ITLYERA==NTLYERA+1)THEN
! OCEAN INTERFACE
    IF(WNDSPD>=0.0D0)THEN
	  RECDATASTREAM(IREC,1)=INDXOCEAN
      RECDATASTREAM(IREC,2)=WNDSPD
      RECDATASTREAM(IREC,3)=RINDX_WATER(IWV)
    ELSE
	  RECDATASTREAM(IREC,1)=1
	  RECDATASTREAM(IREC,2)=1.0D-3
	  RECDATASTREAM(IREC,3)=0.0d0
	ENDIF
    CYCLE
  ENDIF
!  write(*,*)'arslnd1and 2',ITLYERA,ARSLND1(ITLYERA),ARSLND2(ITLYERA)
  IF(ABS(ARSLND1(ITLYERA))<1.0E-32 .AND.ABS(ARSLND2(ITLYERA))<1.0E-32) THEN
     RECDATASTREAM(IREC,1)=ITLYERA
     RECDATASTREAM(IREC,2)=TAUR(IWV,ITLYERA)+TAU_TG(IWV,ITLYERA)        ! TAU
     RECDATASTREAM(IREC,3)=TAUR(IWV,ITLYERA)/RECDATASTREAM(IREC,2) ! ALBEDOR
     RECDATASTREAM(IREC,4)=WV(IWV)
     RECDATASTREAM(IREC,7)= ALT_LYRA(ITLYERA) ! LAYER HEIGHT USE FOR PSEUDO SPHERICAL SHELL CALCULATION

     CALL RAYPHMXASSIGN(NUMMIERT,NUMMIEANGMAX,NUMMIEANGINPUT,PHMXDATASTREAM,ITLYERA,DEPOL_A(IWV,ITLYERA))
     CYCLE
  ENDIF
!call date_and_time(values=time_array_1)
!      finish_time = time_array_1 (5) * 3600 + time_array_1 (6) * 60 &
!           + time_array_1 (7) + 0.001 * time_array_1 (8)
!write(*,*)'spher_interface elapse =',finish_time - start_time
    ! aerosol optical depth

  TAULYR(ITLYERA)=CEXT1*ARSLND1(ITLYERA)+CEXT2*ARSLND2(ITLYERA)
  RTMP= CSCAT1*ARSLND1(ITLYERA)
  RTMP1=RTMP+CSCAT2*ARSLND2(ITLYERA)

  finemoderatio=RTMP/RTMP1
  IF(finemoderatio>1.0D0)finemoderatio=1.0D0
  TAURfrac(ITLYERA)=TAUR(IWV,ITLYERA)/(TAUR(IWV,ITLYERA)+RTMP1)
!  write(*,*)'taurfrac',ITLYERA,TAUR(IWV,ITLYERA),RTMP1
  TAULYR(ITLYERA)=TAULYR(ITLYERA)+TAUR(IWV,ITLYERA)    ! total optical depth=aerosol+rayleigh
  TAULYR(ITLYERA)=TAULYR(ITLYERA)+TAU_TG(IWV,ITLYERA)
  RTMP=CSCAT1*ARSLND1(ITLYERA)+CSCAT2*ARSLND2(ITLYERA)
  LBDOLYR(ITLYERA)=(RTMP+TAUR(IWV,ITLYERA))/TAULYR(ITLYERA)
  PHMXDATASTREAM(ITLYERA,1:NUMMIEANGMAX,1:6)=&
          (1.0d0-finemoderatio)*PHMXDATA_TMP2(IMIE,1:NUMMIEANGMAX,1:6)&
                +finemoderatio *PHMXDATA_TMP1(IMIE,1:NUMMIEANGMAX,1:6)


  ! RAYLEIGH OR AEROSOL LAYERS
  RECDATASTREAM(IREC,1)=ITLYERA
  RECDATASTREAM(IREC,2)=TAULYR(ITLYERA)       ! TAU
  RECDATASTREAM(IREC,3)= LBDOLYR(ITLYERA)     ! ALBEDOR
  RECDATASTREAM(IREC,4)=WV(IWV)
  RECDATASTREAM(IREC,7)= ALT_LYRA(ITLYERA) ! LAYER HEIGHT USE FOR PSEUDO SPHERICAL SHELL CALCULATION

  IF(abs(1.0d0-TAURfrac(ITLYERA))>1.0e-8)THEN
     CALL PHMXMIXING(NUMMIERT,NUMMIEANGMAX,NUMMIEANGINPUT,PHMXDATASTREAM,&
                     ITLYERA,TAURfrac(ITLYERA),DEPOL_A(IWV,ITLYERA))
  ELSE
     CALL RAYPHMXASSIGN(NUMMIERT,NUMMIEANGMAX,NUMMIEANGINPUT,PHMXDATASTREAM,ITLYERA,DEPOL_A(IWV,ITLYERA))
  ENDIF

ENDDO ! LAYER LOOP

RECDATASTREAM(2*(NTLYERA+1)+1,1)=INDXDETECTOR

RECDATASTREAM(2*(NTLYERA+1)+2,1)=1
RECDATASTREAM(2*(NTLYERA+1)+2,2)=1.0D-3
RECDATASTREAM(2*(NTLYERA+1)+2,3)=0.0D0

RECDATASTREAM(2*(NTLYERA+1)+3,1)=INDXLAMB
RECDATASTREAM(2*(NTLYERA+1)+3,3)=1.0d0
RECDATASTREAM(2*(NTLYERA+1)+3,4)=1.34d0

IF(DIFFUSE_TRANSMITTANCE)THEN
   RECDATASTREAM(2*(NTLYERA+1)+3,2)=1.0d0
ELSE
!   IF(WNDSPD>=0.0D0)THEN
      RECDATASTREAM(2*(NTLYERA+1)+3,2)=0.0d0
!   ELSE
!      RECDATASTREAM(2*(NTLYERA+1)+3,2)=0.15d0
!   ENDIF
ENDIF

DEALLOCATE(TAURfrac,TAULYR,LBDOLYR,PHMXDATA_TMP1,PHMXDATA_TMP2)

END SUBROUTINE RTSOSINIT


SUBROUTINE ARSL_VERP_INIT(NTLYERA,ALT_LYRA,PNDLY)
IMPLICIT NONE
INTEGER :: NTLYERA
DOUBLE PRECISION,DIMENSION(NTLYERA+1)::ALT_LYRA
DOUBLE PRECISION,DIMENSION(NTLYERA)::PNDLY
! Vertical distribution is based on Fig. 4 of R.S. Fraser, et al.,
! Algorithm for Atmospheric Correction of Aircraft and Satellite Imagery,
! NASA Technical Memorandum 100751, Dec. 1989.
! the average distribution of Braslau and Dave (1973)
! Braslau, N. and J.V. Dave, 1973: Effect of aerosols on the transfer of solar
! energy through realistic model atmospheres. Part I: Non-absorbing aerosols.,
! J. Appl. Meteor.,l2,601-615.

DOUBLE PRECISION,DIMENSION(8) ::   &
  PND=(/0.0013,0.0727,0.6761,0.8619,0.3735,0.3769,0.9235,193.7308/),&
  HEIGHT=(/45.2205,25.1867,21.8404,20.3539,12.0843,8.0429,4.9380,0./)
DOUBLE PRECISION,DIMENSION(7) :: AEXPFAC,BEXPFAC
DOUBLE PRECISION :: ALTMID
INTEGER :: ILYERA,IHEIGHT

DO IHEIGHT=1,7
  AEXPFAC(IHEIGHT)=-LOG(PND(IHEIGHT)/PND(IHEIGHT+1))/(HEIGHT(IHEIGHT)-HEIGHT(IHEIGHT+1))
  BEXPFAC(IHEIGHT)=PND(IHEIGHT+1)
!  IF(AEXPFAC(IHEIGHT)<0) then
!    WRITE(*,*)IHEIGHT,AEXPFAC(IHEIGHT),LOG(PND(IHEIGHT)/PND(IHEIGHT+1))
!    STOP 'CHECK AEXPFAC'
!  endif
ENDDO

DO ILYERA=1,NTLYERA
 ALTMID=(ALT_LYRA(ILYERA)+ALT_LYRA(ILYERA+1))/2.0
 IF(ALTMID>=HEIGHT(1)) THEN
   PNDLY(ILYERA)=BEXPFAC(1)*EXP(-AEXPFAC(1)*(ALTMID-HEIGHT(2)))
 ELSE IF(ALTMID>=HEIGHT(8)) THEN
   DO IHEIGHT=1,7
     IF(ALTMID<HEIGHT(IHEIGHT) .AND. ALTMID>=HEIGHT(IHEIGHT+1)) EXIT
   ENDDO
   PNDLY(ILYERA)=BEXPFAC(IHEIGHT)*EXP(-AEXPFAC(IHEIGHT)*(ALTMID-HEIGHT(IHEIGHT+1)))
 ELSE
   STOP 'WARNING ALTMID<0'
 ENDIF
!  WRITE(*,*)ALTMID,PNDLY(ILYERA)
ENDDO

DO ILYERA=1,NTLYERA
  PNDLY(ILYERA)=PNDLY(ILYERA)*(ALT_LYRA(ILYERA)-ALT_LYRA(ILYERA+1))
ENDDO

! in the unit of #/micron^2, which is the column number concentration
      !  = (Number of aerosols)/micron^2/km *km where km is the unit of altitude.
!WRITE(*,*)'LAYER INTEGRATED NUMBER DENSITY'
!DO ILYERA=1,NTLYERA
!   ALTMID=(ALT(ILYERA)+ALT(ILYERA+1))/2.0
!   WRITE(*,*)ALTMID,PNDLY(ILYERA),ALT(ILYERA)-ALT(ILYERA+1)
!ENDDO

END SUBROUTINE ARSL_VERP_INIT

SUBROUTINE RAYPHMXASSIGN(NUMMIERT,NUMMIEANGMAX,NUMMIEANGINPUT,PHMXDATASTREAM,&
                         ITLYER,DEPOLRATIO)
USE RTUTILITY,ONLY : FACTOR

IMPLICIT NONE
INTEGER ::    NUMMIERT, NUMMIEANGMAX,ITLYER,ISCATANG
INTEGER,DIMENSION(NUMMIERT) :: NUMMIEANGINPUT
DOUBLE PRECISION,DIMENSION(NUMMIERT,NUMMIEANGMAX,0:6) ::PHMXDATASTREAM
DOUBLE PRECISION,INTENT(IN) :: DEPOLRATIO

DOUBLE PRECISION :: MUF,DELTA_DEPOL,DELTA_DEPOLP

DELTA_DEPOL=(1.0D0-DEPOLRATIO)/(1.0D0+DEPOLRATIO/2.0D0)
DELTA_DEPOLP=(1.0D0-2.0D0*DEPOLRATIO)/(1.0D0-DEPOLRATIO)

DO ISCATANG=1,NUMMIEANGINPUT(ITLYER)
  MUF=COS(PHMXDATASTREAM(ITLYER,ISCATANG,0)*FACTOR)
  PHMXDATASTREAM(ITLYER,ISCATANG,1)=0.75D0*DELTA_DEPOL*(1.0D0+MUF*MUF) &
                                    +1.0D0-DELTA_DEPOL
  PHMXDATASTREAM(ITLYER,ISCATANG,2)=0.75D0*DELTA_DEPOL*(1.0D0+MUF*MUF)
  PHMXDATASTREAM(ITLYER,ISCATANG,3)=1.5D0*DELTA_DEPOL*MUF
  PHMXDATASTREAM(ITLYER,ISCATANG,4)=1.5D0*DELTA_DEPOL*DELTA_DEPOLP*MUF

  PHMXDATASTREAM(ITLYER,ISCATANG,5)=-0.75D0*DELTA_DEPOL*(1.0D0-MUF*MUF)
  PHMXDATASTREAM(ITLYER,ISCATANG,6)=0.0D0
ENDDO

END SUBROUTINE RAYPHMXASSIGN

SUBROUTINE PHMXMIXING(NUMMIERT,NUMMIEANGMAX,NUMMIEANGINPUT,PHMXDATASTREAM,&
                     ITLYER,TAURfracLOCAL,DEPOLRATIO)
USE RTUTILITY,ONLY : FACTOR

IMPLICIT NONE
DOUBLE PRECISION :: DEPOLRATIO
INTEGER ::    NUMMIERT, NUMMIEANGMAX,ITLYER,ISCATANG
INTEGER,DIMENSION(NUMMIERT) :: NUMMIEANGINPUT
DOUBLE PRECISION,DIMENSION(NUMMIERT,NUMMIEANGMAX,0:6) ::PHMXDATASTREAM
DOUBLE PRECISION :: TAURfracLOCAL

DOUBLE PRECISION :: MUF,DELTA_DEPOL,DELTA_DEPOLP
DOUBLE PRECISION,DIMENSION(6):: RAYPHMX_LOCAL

DELTA_DEPOL=(1.0D0-DEPOLRATIO)/(1.0D0+DEPOLRATIO/2.0D0)
DELTA_DEPOLP=(1.0D0-2.0D0*DEPOLRATIO)/(1.0D0-DEPOLRATIO)

DO ISCATANG=1,NUMMIEANGINPUT(ITLYER)
  MUF=COS(PHMXDATASTREAM(ITLYER,ISCATANG,0)*FACTOR)
  RAYPHMX_LOCAL(1)=0.75D0*DELTA_DEPOL*(1.0D0+MUF*MUF)+1.0D0-DELTA_DEPOL

  RAYPHMX_LOCAL(2)=0.75D0*DELTA_DEPOL*(1.0D0+MUF*MUF)
  RAYPHMX_LOCAL(3)=1.5D0*DELTA_DEPOL*MUF
  RAYPHMX_LOCAL(4)=1.5D0*DELTA_DEPOL*DELTA_DEPOLP*MUF

  RAYPHMX_LOCAL(5)=-0.75D0*DELTA_DEPOL*(1.0D0-MUF*MUF)
  RAYPHMX_LOCAL(6)=0.0D0
  PHMXDATASTREAM(ITLYER,ISCATANG,1:6)=TAURfracLOCAL*RAYPHMX_LOCAL(1:6) + &
              (1.0D0-TAURfracLOCAL)*PHMXDATASTREAM(ITLYER,ISCATANG,1:6)
ENDDO

END SUBROUTINE PHMXMIXING


SUBROUTINE TAURCAL(NTLYERA,ALT_LYRA)
USE RTUTILITY, ONLY : PI
USE Atmosphere_Profile, ONLY : NPGRID,P_GRID,Z_FIELD,TEM_FIELD,  &
			NUMDEN_TOTAL_FIELD,VMR_OZONE_FIELD,VMR_OXYGEN_FIELD,     &
			VMR_H2O_FIELD,VMR_CO2_FIELD,VMR_NO2_FIELD,VMR_CH4_FIELD
USE GLOBAL_DATA, only : NWV,WV,TAUR,DEPOL_A

IMPLICIT NONE
INTEGER,INTENT(IN) :: NTLYERA
DOUBLE PRECISION,DIMENSION(NTLYERA+1),INTENT(IN) :: ALT_LYRA
DOUBLE PRECISION :: WAVELENGTH_MICRON

DOUBLE PRECISION,DIMENSION(:),ALLOCATABLE :: TAUR_GRID,TAUR_CUMSUM,DEPOL_GRID

DOUBLE PRECISION, PARAMETER :: C1=400.,C2=450.   !unit ppmv
DOUBLE PRECISION, PARAMETER :: nas_coeff1=5792105D0, nas_coeff2=238.0185D0, &
					 nas_coeff3=167917D0,nas_coeff4=57.362D0
DOUBLE PRECISION, PARAMETER :: nws_coeff0=1.022D0,nws_coeff1=295.235D0,     &
		nws_coeff2=2.6422D0,nws_coeff3=-0.032380D0,nws_coeff4=0.004028D0
DOUBLE PRECISION, PARAMETER :: Mw=0.018015         !unit kg/mol
DOUBLE PRECISION, PARAMETER :: R_Universal=8.31451 !unit: J/mol/K
DOUBLE PRECISION, PARAMETER :: AvogadroNumber=6.022E23
DOUBLE PRECISION :: n_asn1e8,n_asn1,nwsn1e8,nwsn1,rho_ws
DOUBLE PRECISION, DIMENSION(:),ALLOCATABLE :: naxsn1,Ma_profile,Z_func

DOUBLE PRECISION, PARAMETER :: Z_func_a0=1.58123e-6,Z_func_a1=-2.9331e-8,      &
		Z_func_a2=1.1043e-10,Z_func_b0=5.707e-6,Z_func_b1=-2.051e-8, &
		Z_func_c0=1.9898e-4,Z_func_c1=-2.376e-6,                     &
		Z_func_d0=1.83e-11,Z_func_d1=-7.65e-9

DOUBLE PRECISION, PARAMETER :: pressure_standard=101325.,temperature_standard=288.15 ! Kelvin
DOUBLE PRECISION, DIMENSION(:),ALLOCATABLE :: water_mole_number,water_vapor_partial_pressure, &
									rho_axs,rho_a,rho_w,rho_w_ratio,rho_a_ratio,    &
									n_refractive_index,King_Factor
DOUBLE PRECISION :: F1_N2,F2_O2,F3_Ar,F4_CO2,F5_H2O

INTEGER:: ILYERA,IHEIGHT,IWV
DOUBLE PRECISION :: RAY_SCALE_HEIGHT_SUB,RTMP
DOUBLE PRECISION,DIMENSION(:),ALLOCATABLE :: MOLEXT

DOUBLE PRECISION :: Func_UVIP3P

!IF(ATMOS_ZERO)THEN
!	TAUR=1.0D-12
!	DEPOL_A=0.0284d0
!	RETURN
!ENDIF

ALLOCATE(MOLEXT(NPGRID))
ALLOCATE(TAUR_GRID(NPGRID),TAUR_CUMSUM(NPGRID),DEPOL_GRID(NPGRID))

!INITIALIZE MOLEXT THE EXTINCTION COEFFICIENT
ALLOCATE(naxsn1(NPGRID),Ma_profile(NPGRID),Z_func(NPGRID), &
		 water_vapor_partial_pressure(NPGRID),water_mole_number(NPGRID),&
		 rho_axs(NPGRID),rho_a(NPGRID),rho_w(NPGRID),rho_w_ratio(NPGRID), &
		 rho_a_ratio(NPGRID),n_refractive_index(NPGRID),King_Factor(NPGRID))
! INITIALIZE TAUR VALUES
TAUR=0.0D0

DO IWV=1,NWV
WAVELENGTH_MICRON=WV(IWV)
n_asn1e8=nas_coeff1/(nas_coeff2-WAVELENGTH_MICRON**(-2))+nas_coeff3/(nas_coeff4-WAVELENGTH_MICRON**(-2))
n_asn1=n_asn1e8*1.0e-8
naxsn1=n_asn1*(1.0+0.534e-6*(1.0E6*VMR_CO2_FIELD-C2))

nwsn1e8=nws_coeff0*(nws_coeff1+nws_coeff2*WAVELENGTH_MICRON**(-2) &
		+nws_coeff3*WAVELENGTH_MICRON**(-4)+nws_coeff4*WAVELENGTH_MICRON**(-6))
nwsn1=nwsn1e8*1.0e-8

Ma_profile=1.0e-3*(28.9635+12.011e-6*(1.0E6*VMR_CO2_FIELD-C1)) !unit kg/mol

Z_func=1.0-(P_GRID/TEM_FIELD)*                                              &
  (  Z_func_a0+Z_func_a1*(TEM_FIELD-273.15)+Z_func_a2*(TEM_FIELD-273.15)**2 &
   +(Z_func_b0+Z_func_b1*(TEM_FIELD-273.15))*VMR_H2O_FIELD                  &
   +(Z_func_c0+Z_func_c1*(TEM_FIELD-273.15))*VMR_H2O_FIELD**2)              &
   +((P_GRID/TEM_FIELD)**2) * (Z_func_d0+Z_func_d1*VMR_H2O_FIELD**2);

water_mole_number=VMR_H2O_FIELD*NUMDEN_TOTAL_FIELD/AvogadroNumber
water_vapor_partial_pressure=R_Universal*TEM_FIELD*water_mole_number
rho_axs=Ma_profile*pressure_standard/temperature_standard/R_Universal/Z_func
rho_a=Ma_profile*(P_GRID-water_vapor_partial_pressure)/TEM_FIELD/R_Universal/Z_func

rho_ws=Mw*1333/R_Universal/293.15
rho_w=Mw * water_mole_number
rho_w_ratio=rho_w/rho_ws
rho_a_ratio=rho_a/rho_axs

n_refractive_index=1.0+rho_a_ratio*naxsn1+rho_w_ratio*nwsn1

! King factor calculation
F1_N2=1.034+3.17e-4*WAVELENGTH_MICRON**(-2)
F2_O2=1.096+1.385e-3*WAVELENGTH_MICRON**(-2)+1.448e-4*WAVELENGTH_MICRON**(-4)
F3_Ar=1.0
F4_CO2=1.15
F5_H2O=1.001

King_Factor=(0.78084*F1_N2+0.20946*F2_O2+0.0093*F3_Ar +                       &
			 VMR_CO2_FIELD*F4_CO2+water_vapor_partial_pressure/P_GRID*F5_H2O) &
		   /(0.999640+VMR_CO2_FIELD +water_vapor_partial_pressure/P_GRID)

MOLEXT=24*PI**3*King_Factor*(n_refractive_index**2-1.)**2 &
		/(WAVELENGTH_MICRON*1.0e-6)**4 / NUMDEN_TOTAL_FIELD**2 &
		/(n_refractive_index**2+2.)**2;

DEPOL_GRID=6.0*(King_Factor-1.0)/(7.0*King_Factor+3.0)

!MOLEXT=4.5102D-27*(WAVELENGTH_MICRON/0.550D0)**(-4.025D0-0.05627D0*(WAVELENGTH_MICRON/0.550D0)**(-1.647D0))*1.0D-4

IF(ALT_LYRA(1)>Z_FIELD(1)) THEN
	WRITE(*,*)'TAURCAL CHECK, ALT_LYRA(1),Z_FIELD(1)=',ALT_LYRA(1),Z_FIELD(1)
	STOP 'WARNING, ALT_LYRA DATA RANGE LARGER THAN Z_FIELD'
ENDIF
! Z_FIELD IS IN KM
! MULTIPLY BY 1000 TO INTEGRATE AND GET TAUR_GRID
TAUR_CUMSUM=0.0D0
TAUR_GRID=0.0D0
DO IHEIGHT=2,NPGRID
	RAY_SCALE_HEIGHT_SUB=-((Z_FIELD(IHEIGHT-1)-Z_FIELD(IHEIGHT))*1000.0D0)     &
				 /LOG(NUMDEN_TOTAL_FIELD(IHEIGHT-1)/NUMDEN_TOTAL_FIELD(IHEIGHT))
	TAUR_GRID(IHEIGHT)=RAY_SCALE_HEIGHT_SUB                                    &
			*0.5d0*(MOLEXT(IHEIGHT)+MOLEXT(IHEIGHT-1))                         &
			*      (NUMDEN_TOTAL_FIELD(IHEIGHT)-NUMDEN_TOTAL_FIELD(IHEIGHT-1))
	TAUR_CUMSUM(IHEIGHT)=TAUR_CUMSUM(IHEIGHT-1)+TAUR_GRID(IHEIGHT)
ENDDO

DO IHEIGHT=1,NTLYERA
   TAUR(IWV,IHEIGHT)=Func_UVIP3P(NPGRID,Z_FIELD,TAUR_CUMSUM,ALT_LYRA(IHEIGHT+1),3)
   RTMP=0.5d0*(ALT_LYRA(IHEIGHT)+ALT_LYRA(IHEIGHT+1))
   DEPOL_A(IWV,IHEIGHT)=Func_UVIP3P(NPGRID,Z_FIELD,DEPOL_GRID,RTMP,2)

IF(DEPOL_A(IWV,IHEIGHT)<0 .OR. DEPOL_A(IWV,IHEIGHT)>1)THEN
