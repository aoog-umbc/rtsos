	  ELSE
		CEXT1=0.0D0
	  ENDIF
  ELSE
      CEXT=EXTINCTION_CROSS_SECTION_DUSTF(IWVWV_DUST)
      CEXT1=EXTINCTION_CROSS_SECTION_DUSTC(IWVWV_DUST)
  ENDIF

  RTMP=SUM(ARSLND1)*CEXT+SUM(ARSLND2)*CEXT1
  ARSLND1=ARSLND1/RTMP*TAU_REF
  ARSLND2=ARSLND2/RTMP*TAU_REF

  IF((MIE_TABLE_CAL == 3) .AND. IAEROSOL<=20 ) &
	   CALL PART_PHASE_MATRIX_READIN(Mie_Database_Dir,IAEROSOL,AeroFMF,RH_simu) ! MIE_TABLE_CAL IF

  IF((MIE_TABLE_CAL == 1) .AND. IAEROSOL<=20 ) THEN
       CALL PART_PHASE_MATRIX_FILENAME_GEN(Mie_Database_Dir,IAEROSOL,AeroFMF,RH_simu,&
					   Mie_Database_filename)
	   INQUIRE(FILE=Mie_Database_filename, EXIST=file_e)
	   IF(file_e) THEN
           WRITE(*,*)Mie_Database_filename,' EXISTS'
           STOP 'STOPING'
	   ENDIF
  ENDIF

DO IWV=1,NWV


  DELTATAUAINPUT=0.01D0        ! ADJUST FOR ACCURATE OPTICAL INTEGRATION
  DELTATAUOINPUT=0.01D0

call date_and_time(values=time_array_0)
start_time = time_array_0 (5) * 3600 + time_array_0 (6) * 60 &
           + time_array_0 (7) + 0.001 * time_array_0 (8)

write(*,*)'WV(',IWV,')=',WV(IWV)

  CALL RTSOSINIT(IWV,IAEROSOL,RH_simu,ARSLND1,ARSLND2,&
              REFF1,REFF2,VEFF1,VEFF2,MRR1,MRR2,&
              MRI1,MRI2,NREC,TAU_TG,RECDATASTREAM,NTLYER,&
              NTLYERA,ALT_LYRA,NUMMIEUSE,NUMMIERT,  &
              MAXLORDINPUT,NUMMIEANGINPUT,PHMXDATASTREAM,LBDO_LD,FLAM)
IF(MIE_TABLE_CAL == 1) CYCLE
! SAVE OPTICAL DEPTH INFO
DO ILAYER=1,NTLYERA
  TAU_ARSL_TOTAL(IWV,ILAYER)=RECDATASTREAM(2*ILAYER,2)-TAUR(IWV,ILAYER)
ENDDO

call date_and_time(values=time_array_1)
      finish_time = time_array_1 (5) * 3600 + time_array_1 (6) * 60 &
           + time_array_1 (7) + 0.001 * time_array_1 (8)
write(*,*)'rtsosinit elapsed time =', finish_time-start_time

!Open(unit=1,file='recdata',POSITION='append')
!write(1,*)'WV(',IWV,')=',WV(IWV), "NDET=",NDET
!WRITE(1,*)'RECDATASTREAM'
!DO INTTMP=1,NREC
! IPT = RECDATASTREAM(INTTMP,1)
